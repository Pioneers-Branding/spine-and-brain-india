                                        <div class="lead">
                                            <p>A "slipped disc" — more correctly a <strong>herniated</strong> or <strong>prolapsed disc</strong> — is one of the most common causes of back and leg pain. The reassuring news is that most slipped discs are <em>not</em> serious and settle with time and simple treatment. But a minority genuinely are, and knowing which is which can protect you from lasting nerve damage.</p>
                                            <p>This guide, written from a neurosurgeon's perspective, walks you through the signs of a mild versus a serious slipped disc, the red flags that need urgent attention, and how severity is actually assessed.</p>
                                        </div>

                                        <h2>What a Slipped Disc Actually Is</h2>
                                        <p>Between each pair of vertebrae sits a soft, cushioning disc with a tough outer ring and a gel-like centre. When the outer ring weakens, the inner gel can bulge or leak out — this is a herniated or slipped disc. The trouble usually starts not because the disc has moved, but because it presses on a nearby nerve root or, less often, the spinal cord. How serious it is depends almost entirely on <strong>how much a nerve is being affected</strong>.</p>

                                        <h2>Signs of a Milder Slipped Disc</h2>
                                        <p>Most slipped discs cause pain that is unpleasant but manageable and tends to improve over weeks. Reassuring features include:</p>
                                        <ul class="blog-list">
                                            <li>Pain mostly in the back, buttock or one leg that <strong>eases with rest</strong> and changes with position.</li>
                                            <li>Mild tingling or pins-and-needles that comes and goes.</li>
                                            <li>Pain that is <strong>gradually improving</strong> week on week.</li>
                                            <li>Full strength in the leg and foot — you can still walk, climb stairs and stand on tiptoe.</li>
                                            <li>No problems with bladder or bowel control.</li>
                                        </ul>
                                        <p>If this sounds like you, the outlook is good. Around 90% of people in this group recover without surgery.</p>

                                        <h2>Signs Your Slipped Disc May Be Serious</h2>
                                        <p>Certain features suggest the nerve is under significant or increasing pressure and need a specialist's assessment sooner rather than later:</p>
                                        <ul class="blog-list">
                                            <li><strong>Severe leg pain (sciatica)</strong> that shoots below the knee and is worse than the back pain itself.</li>
                                            <li><strong>Persistent or spreading numbness</strong> in the leg or foot.</li>
                                            <li><strong>Muscle weakness</strong> — difficulty lifting the foot, standing on tiptoe, or a leg that feels like it is giving way.</li>
                                            <li>Pain that is <strong>getting worse rather than better</strong> after a few weeks, or that wakes you at night.</li>
                                            <li>Symptoms affecting <strong>both legs</strong>.</li>
                                        </ul>
                                        <p>Serious does not always mean surgery — but it does mean you should be properly evaluated rather than waiting it out.</p>

                                        <div class="redflag-box">
                                            <h2>Red Flags: Get Emergency Care Immediately</h2>
                                            <p>A small number of symptoms point to severe compression of the nerve bundle at the base of the spine (cauda equina syndrome). This is a genuine emergency — delay can cause permanent damage. Go to an emergency department at once if you notice:</p>
                                            <ul class="blog-list">
                                                <li><strong>Loss of bladder or bowel control</strong>, or difficulty passing urine.</li>
                                                <li><strong>Numbness around the groin, buttocks or inner thighs</strong> (saddle area).</li>
                                                <li><strong>Sudden, severe weakness in both legs.</strong></li>
                                                <li>New numbness or weakness that is <strong>rapidly worsening</strong>.</li>
                                            </ul>
                                        </div>

                                        <h2>How Doctors Assess How Serious It Is</h2>
                                        <p>A specialist judges severity from your story and a careful <strong>neurological examination</strong> — testing strength, sensation and reflexes to see which nerve is involved and how badly. When needed, an <strong>MRI scan</strong> gives the clearest picture of the disc, the nerves and the degree of compression. Occasionally a nerve conduction study (NCS/EMG) is added to measure how well the nerve is working. Together these tell the doctor whether the problem is mild and likely to settle, or significant enough to need active treatment.</p>

                                        <h2>What Happens Next: Treatment by Severity</h2>
                                        <p>A milder slipped disc is treated with physiotherapy, guided exercise, staying gently active and short-term medication as advised. A more serious one may add an epidural or nerve-root injection, closer monitoring, and — if there is progressive weakness or the pain fails to settle — a discussion about minimally invasive surgery such as microdiscectomy. The key message is simple: mild symptoms can be watched, but <strong>weakness, spreading numbness or any red-flag sign should be checked promptly</strong> by a spine specialist like <strong>Dr. Arun Saroha</strong>.</p>

